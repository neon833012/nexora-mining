// Fast escape for RegExp matching
function escapeRegExp(string: string) {
  return string.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

// Cache sorted keys by descending length for longest-phrase-first replacement
const sortedKeysByLang: Partial<Record<LanguageCode, string[]>> = {};

function getSortedKeys(lang: LanguageCode): string[] {
  if (!sortedKeysByLang[lang]) {
    const dict = UNIVERSAL_DICTIONARY[lang];
    if (dict) {
      sortedKeysByLang[lang] = Object.keys(dict).sort((a, b) => b.length - a.length);
    } else {
      sortedKeysByLang[lang] = [];
    }
  }
  return sortedKeysByLang[lang]!;
}

// Normalizes whitespace
function clean(str: string): string {
  return str.replace(/\s+/g, ' ').trim();
}

// Pure number, symbol, crypto address & currency protector
function isFinancialOrCryptoToken(txt: string): boolean {
  if (!txt || txt.length < 2) return true;
  // Crypto addresses & hashes (0x..., base58, 20+ chars hex)
  if (txt.startsWith('0x') || /^[A-HJ-NP-Za-km-z1-9]{26,45}$/.test(txt)) return true;
  // Financial amounts: $10, $20.00, +0.50 USDT, 100.00, 2.5%, 19,480, 00:00 UTC
  if (/^[\$€£¥₹+\-]?\s*[\d,]+(?:\.\d+)?(?:\s*(?:USDT|BNB|ETH|BTC|USD|%|GH\/s|TH\/s|MH\/s|UTC))?$/i.test(txt)) return true;
  // Timer strings 00:00:00
  if (/^\d{1,2}:\d{2}(?::\d{2})?$/.test(txt)) return true;
  return false;
}

export function translatePhrase(rawText: string, lang: LanguageCode): string {
  if (!rawText || !rawText.trim() || lang === 'en') return rawText;
  const dict = UNIVERSAL_DICTIONARY[lang];
  if (!dict) return rawText;

  const trimmed = clean(rawText);
  if (isFinancialOrCryptoToken(trimmed)) return rawText;

  const leading = rawText.match(/^\s*/)?.[0] || '';
  const trailing = rawText.match(/\s*$/)?.[0] || '';

  // 1. Exact match (O(1))
  if (dict[trimmed]) {
    return leading + dict[trimmed] + trailing;
  }

  // 2. Case-insensitive match
  const lower = trimmed.toLowerCase();
  for (const [k, v] of Object.entries(dict)) {
    if (k.toLowerCase() === lower) {
      return leading + v + trailing;
    }
  }

  // 3. Substring & compound phrase replacement with longest match first
  const keys = getSortedKeys(lang);
  let res = trimmed;
  let replaced = false;

  for (const k of keys) {
    if (k.length < 2) continue;
    const trans = dict[k];
    if (!trans || trans === k) continue;

    // Multi-word phrase or long word
    if (k.includes(' ') || k.length >= 6) {
      if (res.includes(k)) {
        res = res.split(k).join(trans);
        replaced = true;
      }
    } else {
      // Short single words: use word boundaries to avoid mangling words
      try {
        const regex = new RegExp('\\b' + escapeRegExp(k) + '\\b', 'g');
        if (regex.test(res)) {
          res = res.replace(regex, trans);
          replaced = true;
        }
      } catch (e) {}
    }
  }

  if (replaced) {
    return leading + res + trailing;
  }

  return rawText;
}

// Augment DOM Node with custom original text storage
declare global {
  interface Node {
    __neon_orig?: string;
  }
  interface HTMLInputElement {
    __neon_orig_ph?: string;
  }
  interface HTMLTextAreaElement {
    __neon_orig_ph?: string;
  }
}

export function translateSubtree(root: HTMLElement | Node, lang: LanguageCode) {
  if (!root || typeof document === 'undefined') return;

  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode: (node) => {
      const parent = node.parentElement;
      if (!parent) return NodeFilter.FILTER_REJECT;
      const tag = parent.tagName.toLowerCase();
      if (tag === 'script' || tag === 'style' || tag === 'code' || tag === 'pre') return NodeFilter.FILTER_REJECT;
      if (parent.closest('[translate="no"], .notranslate')) return NodeFilter.FILTER_REJECT;
      const txt = node.nodeValue?.trim();
      if (!txt || txt.length < 2) return NodeFilter.FILTER_REJECT;
      if (isFinancialOrCryptoToken(txt)) return NodeFilter.FILTER_REJECT;
      return NodeFilter.FILTER_ACCEPT;
    }
  });

  let node: Node | null = walker.nextNode();
  while (node) {
    if (node.nodeType === Node.TEXT_NODE) {
      if (node.__neon_orig === undefined) {
        node.__neon_orig = node.nodeValue || '';
      }
      if (lang === 'en') {
        node.nodeValue = node.__neon_orig;
      } else {
        node.nodeValue = translatePhrase(node.__neon_orig, lang);
      }
    }
    node = walker.nextNode();
  }

  // Handle placeholders in form inputs and textareas
  if ((root as HTMLElement).querySelectorAll) {
    const inputs = (root as HTMLElement).querySelectorAll<HTMLInputElement | HTMLTextAreaElement>('input, textarea');
    inputs.forEach((input) => {
      if (input.placeholder) {
        if (input.__neon_orig_ph === undefined) {
          input.__neon_orig_ph = input.placeholder;
        }
        if (lang === 'en') {
          input.placeholder = input.__neon_orig_ph;
        } else {
          input.placeholder = translatePhrase(input.__neon_orig_ph, lang);
        }
      }
    });
  }
}

let globalObserver: MutationObserver | null = null;
let activeObservedLang: LanguageCode = 'en';

export function startUniversalTranslator(lang: LanguageCode) {
  activeObservedLang = lang;
  if (typeof document === 'undefined') return;

  // Immediate translation pass across the document
  translateSubtree(document.body, lang);

  // Re-bind MutationObserver
  if (globalObserver) {
    globalObserver.disconnect();
    globalObserver = null;
  }

  if (lang === 'en') return;

  globalObserver = new MutationObserver((mutations) => {
    for (const m of mutations) {
      if (m.type === 'childList') {
        m.addedNodes.forEach((n) => {
          if (n.nodeType === Node.ELEMENT_NODE) {
            translateSubtree(n as HTMLElement, activeObservedLang);
          } else if (n.nodeType === Node.TEXT_NODE && n.parentElement) {
            if (!n.parentElement.closest('[translate="no"], .notranslate')) {
              if (n.__neon_orig === undefined) n.__neon_orig = n.nodeValue || '';
              n.nodeValue = translatePhrase(n.__neon_orig, activeObservedLang);
            }
          }
        });
      }
    }
  });

  globalObserver.observe(document.body, {
    childList: true,
    subtree: true
  });
}

// Helper for programmatic component text translation
export function t(text: string, lang: LanguageCode = 'en'): string {
  return translatePhrase(text, lang);
}
